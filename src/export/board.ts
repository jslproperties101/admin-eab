type Fmt = 'pdf' | 'xlsx';
const blobOf = async (doc: () => Doc, sheets: () => Sheet[], format: Fmt, title: string, author: string): Promise<Blob> =>
  format === 'pdf'
    ? renderPagesToPdf(layoutDocument(doc(), canvasMeasure()), title)
    : new Blob([buildXlsx(sheets(), { title, author }) as BlobPart], { type: XLSX_MIME });

