export interface BoardInput { reference: string; createdAt: string; adminEmail: string; companyName?: string; contentSha: string; report: BoardReport }

const periodText = (r: BoardReport) => `${monthName(r.month)}${r.complete ? '' : ` (so far, to ${r.current.to})`}`;

export function buildBoardDoc(x: BoardInput): Doc {
  const r = x.report;
  const b: Block[] = [
    { t: 'title', text: 'Monthly Board report', sub: `${x.companyName ? `${x.companyName} · ` : ''}${periodText(r)}` },
    { t: 'rows', rows: [
      { k: 'Reference', v: x.reference, strong: true },
      { k: 'Month', v: periodText(r) },
      { k: 'Compared with', v: monthName(r.previous.from) },
      { k: 'Made', v: `${fmtTime(x.createdAt)} by ${x.adminEmail}` },
      { k: 'Content fingerprint (SHA-256)', v: x.contentSha },
    ] },
    { t: 'text', small: true, muted: true, text: 'Each line: this month, then last month and the change. Lines marked "today" are a count on the day the report was made. Totals only: no agent is named.' },
  ];
  for (const s of boardSections(r)) {
    b.push({ t: 'heading', text: s.title });
    b.push({ t: 'rows', rows: s.lines.map(l => ({
      k: l.sub ? `  ${l.label}` : l.label, sub: l.sub, warn: l.warn,
      v: l.prev === null ? `${l.cur.toLocaleString('en-MY')} today` : `${l.cur.toLocaleString('en-MY')}   ·   last month ${l.prev.toLocaleString('en-MY')}   ·   ${changeText(l.cur, l.prev)}${l.text ? `   ·   ${l.text}` : ''}`,
    })) });
  }
  const states = r.current.listings.by_state_now ?? [];
  if (states.length) {
    b.push({ t: 'heading', text: 'Listings by state today (top 10)' });
    b.push({ t: 'rows', rows: states.map(s => ({ k: s.state, v: s.listings.toLocaleString('en-MY') })) });
  }
  b.push({ t: 'text', small: true, muted: true, text: 'Generated by Admin EAB from the live database (Malaysia dates). This file is kept in the Document Vault under the reference above; its file fingerprint proves any copy is unchanged.' });
  return { blocks: b, footer: `${x.reference} · Board report ${r.month.slice(0, 7)} · content ${shortFp(x.contentSha)}` };
}

export function buildBoardSheets(x: BoardInput): Sheet[] {
  const r = x.report;
  const rows: Cell[][] = [['Section', 'Line', monthName(r.month), monthName(r.previous.from), 'Change', 'Note']];
  for (const s of boardSections(r)) for (const l of s.lines)
    rows.push([s.title, l.label, l.cur, l.prev ?? '', l.prev === null ? 'count today' : changeText(l.cur, l.prev), l.text ?? '']);
  return [
    { name: 'Board report', widths: [22, 52, 16, 16, 16, 30], rows },
    { name: 'About', widths: [30, 70], rows: [
      ['Monthly Board report', x.reference], ['Month', periodText(r)], ['Compared with', monthName(r.previous.from)], ['Company', x.companyName ?? ''],
      ['Made', `${fmtTime(x.createdAt)} by ${x.adminEmail}`], ['Content fingerprint (SHA-256)', x.contentSha],
    ] },
    { name: 'Listings by state', widths: [30, 12], rows: [['State', 'Listings today'], ...(r.current.listings.by_state_now ?? []).map(s => [s.state, s.listings] as Cell[])] },
  ];
}
export const boardFileName = (month: string, reference: string, ext: Fmt) => `Board-report-${month.slice(0, 7)}-${reference}.${ext}`;

/** Gets the numbers, registers the export, makes the file, keeps it in the vault and saves a copy here. */
export async function exportBoardReport(api: Api, adminEmail: string, month: string, format: Fmt, onStep: (s: string) => void = () => {}): Promise<{ pack: Pack; how: string }> {
  onStep('Counting…');
  const [report, companyName] = await Promise.all([api.boardReport(month), api.settings().then(s => s.company_name).catch(() => undefined)]);
  const contentSha = await contentFingerprint(report);
  onStep('Registering the export…');
  const reg = await api.startExport('board_report', format, null, { month: report.month, content_sha256: contentSha });
  const input: BoardInput = { reference: reg.reference, createdAt: reg.at, adminEmail, companyName, contentSha, report };
  onStep(format === 'pdf' ? 'Making the PDF…' : 'Making the Excel file…');
  const blob = await blobOf(() => buildBoardDoc(input), () => buildBoardSheets(input), format, `Board report ${report.month.slice(0, 7)} ${reg.reference}`, adminEmail);
  const name = boardFileName(report.month, reg.reference, format);
  onStep('Storing in the Document Vault…');
  const pack = await storeInVault(api, { blob, reference: reg.reference, kind: 'board_report', format, fileName: name, caseId: null, agentUser: null, contentSha });
  onStep('Saving a copy…');
  return { pack, how: await saveLocally(blob, name) };
}

