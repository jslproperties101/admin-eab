export const auditFileName = (year: number, reference: string, ext: Fmt) => `Audit-bundle-${year}-${ext === 'xlsx' ? 'workbook' : 'summary'}-${reference}.${ext}`;

/** Makes the workbook, then the PDF summary that names it; both go to the vault and are saved here. */
export async function exportAuditBundle(api: Api, adminEmail: string, year: number, onStep: (s: string) => void = () => {}): Promise<{ workbook: Pack; summary: Pack; how: string[] }> {
  onStep('Collecting the year…');
  const [bundle, companyName] = await Promise.all([api.auditBundle(year), api.settings().then(s => s.company_name).catch(() => undefined)]);
  const contentSha = await contentFingerprint(bundle);
  onStep('Registering the workbook…');
  const regX = await api.startExport('audit_bundle', 'xlsx', null, { year, content_sha256: contentSha });
  const inX: AuditInput = { reference: regX.reference, createdAt: regX.at, adminEmail, companyName, contentSha, bundle };
  onStep('Making the Excel workbook…');
  const xBlob = new Blob([buildXlsx(buildAuditSheets(inX), { title: `Audit bundle ${year} ${regX.reference}`, author: adminEmail }) as BlobPart], { type: XLSX_MIME });
  const xName = auditFileName(year, regX.reference, 'xlsx');
  onStep('Storing the workbook in the Document Vault…');
  const workbook = await storeInVault(api, { blob: xBlob, reference: regX.reference, kind: 'audit_bundle', format: 'xlsx', fileName: xName, caseId: null, agentUser: null, contentSha });
  const how = [await saveLocally(xBlob, xName)];
  onStep('Registering the summary…');
  const regP = await api.startExport('audit_bundle', 'pdf', null, { year, content_sha256: contentSha, workbook: regX.reference });
  const inP: AuditInput = { ...inX, reference: regP.reference, createdAt: regP.at };
  onStep('Making the PDF summary…');
  const pBlob = await renderPagesToPdf(layoutDocument(buildAuditDoc(inP, { reference: regX.reference, sha256: workbook.sha256 }), canvasMeasure()), `Audit bundle ${year} ${regP.reference}`);
  const pName = auditFileName(year, regP.reference, 'pdf');
  onStep('Storing the summary in the Document Vault…');
  const summary = await storeInVault(api, { blob: pBlob, reference: regP.reference, kind: 'audit_bundle', format: 'pdf', fileName: pName, caseId: null, agentUser: null, contentSha });
  how.push(await saveLocally(pBlob, pName));
  return { workbook, summary, how };
}

