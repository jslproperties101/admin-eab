export interface CustomInput { reference: string; createdAt: string; adminEmail: string; companyName?: string; name: string; spec: ReportSpec; src: ReportSource; result: ReportResult }
export const PDF_ROW_CAP = 1000;

/** The report's settings in words, e.g. "Listings · grouped by State · How many · State contains "Sel" · from 2026-10-01". */
export function specText(spec: ReportSpec, src: ReportSource): string[] {
  const l = (k: string) => src.columns[k]?.l ?? k;
  const out = [src.label];
  if (spec.group_by?.length) out.push(`grouped by ${spec.group_by.map(l).join(' and ')} · ${measureLabel(spec.measure, src)}`);
  else out.push(`columns: ${(spec.columns ?? []).map(l).join(', ')}`);
  if (spec.from || spec.to) out.push(`${l(src.date)} ${spec.from ? `from ${spec.from}` : ''}${spec.from && spec.to ? ' ' : ''}${spec.to ? `to ${spec.to}` : ''}`);
  for (const f of spec.filters ?? []) out.push(`${l(f.col)} ${OP_LABEL[f.op]} ${f.op === 'is' ? IS_VALUES[String(f.value)] ?? f.value : Array.isArray(f.value) ? f.value.join(', ') : `"${f.value}"`}`);
  if (spec.sort) out.push(`sorted by ${spec.sort.by === 'value' ? measureLabel(spec.measure, src) : l(spec.sort.by)} (${spec.sort.dir === 'asc' ? 'lowest first' : 'highest first'})`);
  return out;
}

export function buildCustomDoc(x: CustomInput): Doc {
  const h = resultHeaders(x.spec, x.src); const rows = x.result.rows.slice(0, PDF_ROW_CAP);
  const grouped = !!x.spec.group_by?.length;
  const b: Block[] = [
    { t: 'title', text: x.name || 'Custom report', sub: `${x.companyName ? `${x.companyName} · ` : ''}Custom report · ${x.src.label}` },
    { t: 'rows', rows: [
      { k: 'Reference', v: x.reference, strong: true },
      { k: 'Made', v: `${fmtTime(x.createdAt)} by ${x.adminEmail}` },
      { k: 'Report', v: specText(x.spec, x.src).join(' · ') },
      { k: 'Rows', v: `${x.result.count.toLocaleString('en-MY')}${x.result.truncated ? ' (more exist: raise the row limit or add filters)' : ''}${x.result.rows.length > PDF_ROW_CAP ? ` — this PDF shows the first ${PDF_ROW_CAP}; the Excel file has them all` : ''}`, warn: x.result.truncated },
    ] },
    { t: 'heading', text: grouped ? `${h.slice(0, -1).map(c => c.label).join(' · ')} → ${h[h.length - 1].label}` : 'Rows' },
    { t: 'rows', rows: rows.map(r => grouped
      ? { k: h.slice(0, -1).map(c => cellText(r[c.key], c.t, c.key)).join(' · '), v: cellText(r.value, 'num') }
      : { k: cellText(r[h[0].key], h[0].t, h[0].key), v: h.slice(1).map(c => `${c.label}: ${cellText(r[c.key], c.t, c.key)}`).join('  ·  ') }) },
    { t: 'text', small: true, muted: true, text: 'Made with the Admin EAB report builder from the live database. The export is recorded in the tamper-proof access log under the reference above.' },
  ];
  return { blocks: b, footer: `${x.reference} · ${x.name || 'Custom report'} · ${fmtTime(x.createdAt)}` };
}

export function buildCustomSheets(x: CustomInput): Sheet[] {
  const h = resultHeaders(x.spec, x.src);
  return [
    { name: 'Report', widths: h.map(c => (c.t === 'text' ? 28 : 14)), rows: [h.map(c => c.label), ...x.result.rows.map(r => h.map(c => cellValue(r[c.key], c.t, c.key)))] },
    { name: 'About', widths: [20, 90], rows: [
      ['Custom report', x.name || ''], ['Reference', x.reference], ['Made', `${fmtTime(x.createdAt)} by ${x.adminEmail}`], ['Company', x.companyName ?? ''],
      ['Rows', x.result.truncated ? `${x.result.count} (more exist)` : x.result.count], [], ['Settings'], ...specText(x.spec, x.src).map(t => ['', t] as Cell[]),
    ] },
  ];
}
const slug = (s: string) => s.replace(/[^A-Za-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40) || 'report';
export const customFileName = (name: string, reference: string, ext: Fmt) => `Report-${slug(name)}-${reference}.${ext}`;

/** Registers the export (owner / compliance), makes the file from what is on screen and saves it here. */
export async function exportCustomReport(api: Api, adminEmail: string, format: Fmt, name: string, spec: ReportSpec, src: ReportSource, result: ReportResult): Promise<{ reference: string; how: string }> {
  const companyName = await api.settings().then(s => s.company_name).catch(() => undefined);
  const reg = await api.startExport('custom_report', format, null, { source: spec.source, name, rows: result.count, spec });
  const input: CustomInput = { reference: reg.reference, createdAt: reg.at, adminEmail, companyName, name, spec, src, result };
  const blob = await blobOf(() => buildCustomDoc(input), () => buildCustomSheets(input), format, `${name || 'Custom report'} ${reg.reference}`, adminEmail);
  return { reference: reg.reference, how: await saveLocally(blob, customFileName(name, reg.reference, format)) };
}
