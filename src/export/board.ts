const yn = (b: boolean | null | undefined) => (b ? 'Yes' : 'No');
const answerDays = (p: { received_on: string; supplied_on: string | null; decided_on: string | null }) => {
  const end = p.supplied_on ?? p.decided_on; return end ? daysSince(p.received_on, end) : null;
};
const late = (p: { kind: string; received_on: string; supplied_on: string | null; decided_on: string | null }, today: string) =>
  hasDeadline(p.kind as never) && (daysSince(p.received_on, p.supplied_on ?? p.decided_on ?? today) ?? 0) > 21;

export function auditCounts(b: AuditBundle, today: string) {
  return {
    actions: b.counts.actions, access: b.counts.access, actionsCut: b.counts.actions > b.actions.length, accessCut: b.counts.access > b.access.length,
    restoreTests: b.backup_tests.filter(t => t.kind === 'restore_test').length, failedTests: b.backup_tests.filter(t => t.result !== 'pass').length,
    cases: b.cases.length, packs: b.vault.length, pdpa: b.pdpa.length, pdpaLate: b.pdpa.filter(p => late(p, today)).length,
    complaints: b.complaints.length, holds: b.holds.length, holdsActive: b.holds.filter(h => !h.released_at).length, reviews: b.retention_reviews.length,
    chainOk: !!(b.chain.actions?.ok && b.chain.access?.ok),
  };
}

