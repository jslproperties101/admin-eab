// AdminBatch011 — Money report (PDF / Excel): profit & loss and cost per user by month, the ledger, Google API use and
// estimated cost with quota alerts. Owner and Compliance only (the database refuses anyone else). Saved on this device,
// not in the Document Vault (same as the other dashboard reports). Pure builders, so they are unit-tested.
import { Block, Doc, layoutDocument } from '../lib/pdf';
import { canvasMeasure, renderPagesToPdf } from '../lib/pdfRender';
import { Api, ApiUsage, Ledger, MoneySummary } from '../api/admin';
import { Sheet, buildXlsx, XLSX_MIME } from './xlsx';
import { fmtTime } from './reports';
import { saveLocally } from './pack';
import { fmtNum } from '../admin/dash';
import { monthLabel } from '../admin/market';
import { LEVEL_LABEL, categoryLabel, fmtMyr, fmtUsd, googleNameLabel } from '../admin/money';
import { todayKL } from '../admin/health';

export interface MoneyData { summary: MoneySummary; ledger: Ledger; usage: ApiUsage }
export interface MoneyReportInput { reference: string; createdAt: string; adminEmail: string; companyName?: string; data: MoneyData }

export function buildMoneyDoc(x: MoneyReportInput): Doc {
  const { summary: s, ledger: l, usage: u } = x.data;
  const b: Block[] = [
    { t: 'title', text: 'Money report', sub: `${x.companyName ?? ''}${x.companyName ? ' · ' : ''}Estate Agent AI Buddy` },
    { t: 'rows', rows: [
      { k: 'Reference', v: x.reference, strong: true },
      { k: 'Period', v: `${monthLabel(s.since.slice(0, 7))} to this month (${s.months} months, Malaysia dates)` },
      { k: 'Made', v: `${fmtTime(x.createdAt)} by ${x.adminEmail}` },
      { k: 'Contains', v: 'Profit & loss, cost per active agent, every ledger entry (voided ones marked), Google API use and estimated cost.' },
    ] },
    { t: 'heading', text: 'Profit & loss' },
    { t: 'rows', rows: [
      { k: 'Received', v: fmtMyr(s.income) }, { k: 'Paid', v: fmtMyr(s.expenses) },
      { k: s.net < 0 ? 'Loss' : 'Profit', v: fmtMyr(s.net), strong: true, warn: s.net < 0 },
      ...s.by_month.map(m => ({ k: `  ${monthLabel(m.month)}`, v: `received ${fmtMyr(m.income)} · paid ${fmtMyr(m.expenses)} · net ${fmtMyr(m.net)}${m.over_budget ? ' · over warning' : ''}`, sub: true, warn: m.net < 0 })),
    ] },
    { t: 'heading', text: 'Cost per active agent' },
    { t: 'rows', rows: [
      { k: 'Average per agent per month', v: fmtMyr(s.cost_per_active_avg), strong: true },
      { k: 'Average active agents', v: s.average_active === null ? '—' : fmtNum(s.average_active, 1) },
      ...s.by_month.filter(m => m.active > 0).map(m => ({ k: `  ${monthLabel(m.month)}`, v: `${fmtMyr(m.cost_per_active)} (${m.active} agents)`, sub: true })),
      ...s.by_category.filter(c => c.kind === 'expense').map(c => ({ k: `  ${categoryLabel(c.category)}`, v: `${fmtMyr(c.per_active)} per agent-month · total ${fmtMyr(c.amount_myr)}`, sub: true })),
    ] },
    { t: 'heading', text: 'Billing & expenses (ledger)' },
    { t: 'rows', rows: [
      { k: 'Paid / received', v: `${fmtMyr(l.expenses_myr)} / ${fmtMyr(l.income_myr)} · ${l.voided} voided entries (not counted)` },
      ...l.entries.slice(0, 300).map(e => ({ k: `  ${e.ref} · ${e.period_month.slice(0, 7)}`,
        v: `${e.kind === 'income' ? '+' : ''}${fmtMyr(e.amount_myr)} · ${categoryLabel(e.category)} · ${e.payee}${e.currency !== 'MYR' ? ` (${e.currency} ${e.amount} at ${e.fx_to_myr})` : ''}${e.voided_at ? ` · VOID: ${e.void_reason}` : ''}`,
        sub: true, warn: !!e.voided_at })),
    ] },
    { t: 'heading', text: 'Google API (estimate from counted calls)' },
    { t: 'rows', rows: [
      { k: 'Estimated bill this month', v: `${fmtUsd(u.month_usd)}${u.usd_myr ? ` (${fmtMyr(u.month_myr)})` : ''} · projected ${fmtUsd(u.projected_usd)}`, strong: true },
      { k: 'Alerts', v: fmtNum(u.alerts), warn: u.alerts > 0 },
      ...u.products.map(p => ({ k: `  ${p.label}`, v: `${fmtNum(p.month_calls)} calls · ${p.price_per_1000 === null ? 'price not set' : fmtUsd(p.month_usd)} · ${LEVEL_LABEL[p.level]}${p.reasons.length ? ` (${p.reasons.join('; ')})` : ''}`,
        sub: true, warn: p.level !== 'ok' })),
    ] },
    { t: 'text', text: 'The Google figures are estimates from the calls the main app counted; the Google Cloud bill is the real amount and is entered in the ledger. Subscription revenue is not built in the main app yet.', small: true },
    { t: 'text', text: 'Generated by Admin EAB from the live database. This export is recorded in the tamper-proof access log under the reference above.', small: true, muted: true },
  ];
  return { blocks: b, footer: `${x.reference} · Money report · ${fmtTime(x.createdAt)}` };
}

export function buildMoneySheets(x: MoneyReportInput): Sheet[] {
  const { summary: s, ledger: l, usage: u } = x.data;
  return [
    { name: 'Summary', widths: [36, 40], rows: [
      ['Money report', x.reference], ['Made', `${fmtTime(x.createdAt)} by ${x.adminEmail}`], ['Company', x.companyName ?? ''],
      [], ['Received RM', s.income], ['Paid RM', s.expenses], ['Profit / loss RM', s.net], ['Cost per agent per month RM', s.cost_per_active_avg ?? ''],
      ['US$ 1 = RM', s.usd_myr ?? 'not set'], ['Monthly spending warning RM', s.monthly_budget_myr ?? 'off'],
      ['Google estimate this month US$', u.month_usd ?? ''], ['Google alerts', u.alerts],
    ] },
    { name: 'By month', widths: [12, 14, 14, 14, 12, 14, 16, 12], rows: [
      ['Month', 'Received RM', 'Paid RM', 'Net RM', 'Active agents', 'Per agent RM', 'Google estimate US$', 'Google billed'],
      ...s.by_month.map(m => [m.month, m.income, m.expenses, m.net, m.active, m.cost_per_active ?? '', m.google_usd ?? '', m.google_billed ? 'yes' : 'no']),
    ] },
    { name: 'Ledger', widths: [16, 10, 10, 30, 30, 30, 8, 14, 10, 14, 12, 8, 18, 30], rows: [
      ['Reference', 'Month', 'Paid on', 'Kind / category', 'Payee', 'Note', 'Currency', 'Amount', 'Rate', 'Amount RM', 'Invoice', 'Monthly', 'Entered by', 'Void'],
      ...l.entries.map(e => [e.ref, e.period_month.slice(0, 7), e.paid_on, `${e.kind === 'income' ? 'Received' : 'Paid'}: ${categoryLabel(e.category)}`, e.payee,
        e.description ?? '', e.currency, Number(e.amount), Number(e.fx_to_myr), Number(e.amount_myr), e.invoice_ref ?? '', e.recurring ? 'yes' : '',
        e.created_by_email ?? '', e.voided_at ? `${fmtTime(e.voided_at)}: ${e.void_reason ?? ''}` : '']),
    ] },
    { name: 'Google API', widths: [34, 12, 14, 14, 12, 12, 12, 12, 12, 40], rows: [
      ['Product', 'Calls', 'Projected', 'Price/1000 US$', 'Free/month', 'Bill US$', 'Projected US$', 'Monthly limit', 'Daily limit', 'Alert'],
      ...u.products.map(p => [p.label, p.month_calls, p.projected, p.price_per_1000 ?? 'not set', p.free_per_month ?? '', p.month_usd ?? '', p.projected_usd ?? '',
        p.monthly_limit ?? '', p.daily_limit ?? '', `${LEVEL_LABEL[p.level]}${p.reasons.length ? `: ${p.reasons.join('; ')}` : ''}`]),
      [], ['Month', 'Calls', 'Failed', 'Estimate US$'], ...u.by_month.map(m => [m.month, m.calls, m.failures, m.usd ?? '']),
      [], ['Call', 'Calls this month', 'Failed', 'Agents'], ...u.by_name.map(n => [googleNameLabel(n.name), n.calls, n.failures, n.agents]),
    ] },
  ];
}

export const moneyFileName = (reference: string, ext: 'pdf' | 'xlsx') => `Money-${reference}.${ext}`;

/** Gathers the last 12 months, registers the export (reference + access log), makes the file, saves it here. */
export async function exportMoney(api: Api, adminEmail: string, format: 'pdf' | 'xlsx'): Promise<{ reference: string; how: string }> {
  const today = todayKL();
  const from = `${String(Number(today.slice(0, 4)) - 1)}${today.slice(4, 7)}-01`;
  const [summary, ledger, usage, companyName] = await Promise.all([
    api.moneySummary(12), api.ledger(from, today, null, true), api.apiUsage(12), api.settings().then(s => s.company_name).catch(() => undefined),
  ]);
  const reg = await api.startExport('money_report', format, null, { from, to: today });
  const input: MoneyReportInput = { reference: reg.reference, createdAt: reg.at, adminEmail, companyName, data: { summary, ledger, usage } };
  const name = moneyFileName(reg.reference, format);
  const blob = format === 'pdf'
    ? await renderPagesToPdf(layoutDocument(buildMoneyDoc(input), canvasMeasure()), `Money report ${reg.reference}`)
    : new Blob([buildXlsx(buildMoneySheets(input), { title: `Money report ${reg.reference}`, author: adminEmail }) as BlobPart], { type: XLSX_MIME });
  return { reference: reg.reference, how: await saveLocally(blob, name) };
}
